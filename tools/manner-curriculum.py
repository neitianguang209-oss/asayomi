rows = []
for gi, (genre, subs) in enumerate(C, 1):
    o = 0
    for sub, topics in subs:
        for t in topics:
            o += 1
            rows.append((genre, sub, t, gi * 1000 + o))
esc = lambda s: s.replace("'", "''")
sql = ["-- マナーのカリキュラム(tools/manner-curriculum.py が書き出す)。同じテーマは入れ直さない",
       "insert into public.asayomi_curriculum(kind, genre, sub, topic, ord) values"]
sql.append(',\n'.join(f"('manner', '{esc(g)}', '{esc(s)}', '{esc(t)}', {o})" for g, s, t, o in rows))
sql.append("on conflict (kind, topic) do update set genre = excluded.genre, sub = excluded.sub, ord = excluded.ord;")
out = os.path.join(os.path.dirname(__file__), '..', 'supabase', 'manner-curriculum.sql')
io.open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(sql) + '\n')
print(len(C), 'genres', len(rows), 'topics')
